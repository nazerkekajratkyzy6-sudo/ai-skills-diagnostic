export type TKey = keyof Dict
const dicts: Record<Lang, Dict> = { kk, ru }

type Ctx = { lang: Lang; setLang: (l: Lang) => void; t: (k: TKey, vars?: Record<string, string | number>) => string }
const I18nCtx = createContext<Ctx>(null as unknown as Ctx)

function readLang(): Lang {
  try {
    const v = localStorage.getItem('aisd_lang')
    if (v === 'kk' || v === 'ru') return v
  } catch { /* ignore */ }
  return 'kk'
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(readLang)
  useEffect(() => { document.documentElement.lang = lang }, [lang])
  const setLang = (l: Lang) => {
    setLangState(l)
    try { localStorage.setItem('aisd_lang', l) } catch { /* ignore */ }
  }
  const t = (k: TKey, vars?: Record<string, string | number>) => {
    let s: string = dicts[lang][k] ?? k
    if (vars) for (const [n, v] of Object.entries(vars)) s = s.split(`{${n}}`).join(String(v))
    return s
  }
  return <I18nCtx.Provider value={{ lang, setLang, t }}>{children}</I18nCtx.Provider>
}

export const useI18n = () => useContext(I18nCtx)

/** Дерекқордағы екі тілді өрісті таңдау: obj.title_kk / obj.title_ru */
export function pick(obj: object | null | undefined, field: string, lang: Lang): string {
  if (!obj) return ''
  const o = obj as Record<string, unknown>
  const v = o[`${field}_${lang}`] || o[`${field}_${lang === 'kk' ? 'ru' : 'kk'}`]
  return (v as string) ?? ''
}

export function LangSwitch({ compact = false }: { compact?: boolean }) {
  const { lang, setLang, t } = useI18n()
  return (
    <div className={'lang-switch' + (compact ? ' compact' : '')} role="group" aria-label="Language">
      <button type="button" className={lang === 'kk' ? 'on' : ''} aria-pressed={lang === 'kk'} onClick={() => setLang('kk')}>{t('lang_kk')}</button>
      <span aria-hidden="true">|</span>
      <button type="button" className={lang === 'ru' ? 'on' : ''} aria-pressed={lang === 'ru'} onClick={() => setLang('ru')}>{t('lang_ru')}</button>
    </div>
  )
}
